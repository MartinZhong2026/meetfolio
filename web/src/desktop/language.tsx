export function translate(key: string, lang: UILanguage, values?: Record<string, string | number>): string {
  const source = lang === 'zh-CN' ? (zhCN[key] ?? key) : key;
  return source.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
}
interface LanguageAPI {
  lang: UILanguage;
  setLang: (next: UILanguage) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}
const Context = createContext<LanguageAPI | null>(null);
function readInitialLanguage(): UILanguage {
  try { return localStorage.getItem(STORAGE_KEY) === 'zh-CN' ? 'zh-CN' : 'en'; }
  catch { return 'en'; }
}
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<UILanguage>(readInitialLanguage);
  useEffect(() => {
    document.documentElement.lang = lang === 'zh-CN' ? 'zh-CN' : 'en';
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* private storage may be unavailable */ }
  }, [lang]);
  const api = useMemo<LanguageAPI>(() => ({ lang, setLang, t: (key, values) => translate(key, lang, values) }), [lang]);
  return <Context.Provider value={api}>{children}</Context.Provider>;
}
export function useLanguage(): LanguageAPI {
  const context = useContext(Context);
  if (!context) throw new Error('Meetfolio language provider is missing.');
  return context;
}
